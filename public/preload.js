const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  startBot: () => ipcRenderer.invoke('start-bot'),
  stopBot: () => ipcRenderer.invoke('stop-bot'),
  authorizeTwitch: () => ipcRenderer.invoke('authorize-twitch'),
  authorizeTwitchDirect: () => ipcRenderer.invoke('authorize-twitch-direct'),
  saveAuthSettings: (payload) => ipcRenderer.invoke('save-auth-settings', payload),
  reloadConfig: () => ipcRenderer.invoke('reload-config'),
  getCollections: (search) => ipcRenderer.invoke('get-collections', search),
  getUserCollection: (userId) => ipcRenderer.invoke('get-user-collection', userId),
  validateRarities: () => ipcRenderer.invoke('validate-rarities'),
  getBotStatus: () => ipcRenderer.invoke('get-bot-status'),
  getLogs: () => ipcRenderer.invoke('get-logs'),
  getConfig: () => ipcRenderer.invoke('get-config'),
  saveConfig: (config) => ipcRenderer.invoke('save-config', config),
  setClientId: (clientId) => ipcRenderer.invoke('set-client-id', clientId),
  getCard: (userId) => ipcRenderer.invoke('get-card', userId),
  getCardsList: () => ipcRenderer.invoke('get-cards-list'),
  saveCardsList: (cards) => ipcRenderer.invoke('save-cards-list', cards),
  saveCardImage: (filename, imageData) => ipcRenderer.invoke('save-card-image', filename, imageData),
  readImageFile: (filePath) => ipcRenderer.invoke('read-image-file', filePath),
  getImageAsBase64: (relativePath) => ipcRenderer.invoke('get-image-as-base64', relativePath),
  moveImageFile: (oldPath, newFilename) => ipcRenderer.invoke('move-image-file', oldPath, newFilename),
  openFileDialog: () => ipcRenderer.invoke('open-file-dialog'),
  getCardsDir: () => ipcRenderer.invoke('get-cards-dir'),
  openCardsDir: () => ipcRenderer.invoke('open-cards-dir'),
  openDataDir: () => ipcRenderer.invoke('open-data-dir'),
  getAppInfo: () => ipcRenderer.invoke('get-app-info'),
  completeOnboarding: () => ipcRenderer.invoke('complete-onboarding'),
  exportUserBackup: () => ipcRenderer.invoke('export-user-backup'),
  importUserBackup: () => ipcRenderer.invoke('import-user-backup'),
  resetCollections: (payload) => ipcRenderer.invoke('reset-collections', payload),
  applyRarityRename: (from, to) => ipcRenderer.invoke('apply-rarity-rename', { from, to }),
  openExternalUrl: (url) => ipcRenderer.invoke('open-external-url', url),
  simulateLogs: () => ipcRenderer.invoke('simulate-logs'),
  onBotStatusChanged: (callback) => ipcRenderer.on('bot-status-changed', (event, data) => callback(data)),
  onNewLog: (callback) => ipcRenderer.on('new-log', (event, message) => callback(message)),
  onLogsUpdated: (callback) => ipcRenderer.on('logs-updated', (event, logs) => callback(logs)),
});
